import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
test('saved views, cancellation, reset, inventory images and mobile',async({page,context})=>{
 await context.request.post('/api/auth/sign-in',{data:{identifier:process.env.GOOB_INVENTORY_TEST_USER,password:'test-browser-password'}});
 await page.route('**/api/config',r=>r.fulfill({json:{authenticated:true,localDemo:false,databaseBacked:true,browserKey:'',routes:false,voice:false}}));
 // No provider request is permitted in this test.
 await page.route('**/invoices/generate',r=>{throw new Error('Unexpected Gemini call');});
 await page.goto('/inventory');
 await expect(page.getByRole('button',{name:'Customize view',exact:true})).toBeEnabled();
 await expect(page.locator('.inventory-table')).toBeVisible();
 await expect(page.locator('.product-image img').first()).toBeVisible();
 const before=await (await context.request.get('/api/dispatch')).json();
 await page.getByRole('button',{name:'Customize view',exact:true}).click();
 const drawer=page.getByRole('dialog',{name:'Customize view'});
 await drawer.getByLabel('Spacing',{exact:true}).selectOption('compact');
 await drawer.getByLabel('Presentation',{exact:true}).selectOption('card');
 await drawer.getByLabel('Theme',{exact:true}).selectOption('after-hours');
 await expect(page.locator('.inventory-cards')).toBeVisible();
 await drawer.getByLabel('New view name').fill('Night shift');
 await drawer.getByRole('button',{name:'Save as',exact:true}).click();
 await expect(drawer).not.toBeVisible();
 await page.reload();
 await expect(page.locator('.goob-view')).toHaveClass(/theme-after-hours/);
 await expect(page.locator('.inventory-cards')).toBeVisible();
 await expect(page.getByLabel('Saved view')).toHaveValue('Night shift');
 await page.getByLabel('Saved view').selectOption('Default');
 await expect(page.locator('.goob-view')).toHaveClass(/theme-fieldbook/);
 await page.getByLabel('Saved view').selectOption('Night shift');
 await expect(page.locator('.goob-view')).toHaveClass(/theme-after-hours/);
 await page.getByRole('button',{name:'Customize view',exact:true}).click();
 await drawer.getByLabel('Theme',{exact:true}).selectOption('workshop');
 await drawer.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.locator('.goob-view')).toHaveClass(/theme-after-hours/);
 await page.getByRole('button',{name:'Customize view',exact:true}).click();
 await drawer.getByRole('button',{name:'Reset',exact:true}).click();
 await expect(page.locator('.inventory-table')).toBeVisible();
 await drawer.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.locator('.inventory-cards')).toBeVisible();
 await page.getByRole('button',{name:'List',exact:true}).click();
 await expect(page.locator('.inventory-table')).toBeVisible();
 await page.getByLabel('Search inventory').fill('Circuit');
 await page.getByRole('button',{name:'Cards',exact:true}).click();
 await expect(page.getByLabel('Search inventory')).toHaveValue('Circuit');
 await page.getByRole('button',{name:'View item / history',exact:true}).first().click();
 await expect(page.locator('.inventory-detail')).toBeVisible();
 await page.getByRole('button',{name:'Replace image',exact:true}).click();
 const image=page.getByRole('dialog',{name:'Replace product image'});
 await page.route('https://images.example.com/breaker.webp',async r=>r.fulfill({body:await readFile('public/inventory-images/breaker.webp'),contentType:'image/webp'}));
 await image.getByLabel('Image URL',{exact:true}).fill('https://images.example.com/breaker.webp');
 await image.getByLabel('Alt text').fill('Updated circuit breaker image');
 await image.getByRole('button',{name:'Save image'}).click();
 await expect(image).not.toBeVisible();
 await expect(page.getByAltText('Updated circuit breaker image')).toBeVisible();
 await page.reload();
 await expect(page.getByAltText('Updated circuit breaker image')).toBeVisible();
 const after=await (await context.request.get('/api/dispatch')).json();
 expect(after.state.stock.map((i:any)=>[i.id,i.quantity,i.reservedQuantity,i.threshold])).toEqual(before.state.stock.map((i:any)=>[i.id,i.quantity,i.reservedQuantity,i.threshold]));
 await page.route('https://images.example.com/breaker.webp',r=>r.abort());
 await page.reload();
 await expect(page.getByRole('img',{name:/No image available/})).toBeVisible();
 await context.request.post('/api/auth/sign-out');
 await context.request.post('/api/auth/sign-in',{data:{identifier:process.env.GOOB_INVENTORY_TEST_USER,password:'test-browser-password'}});
 await page.goto('/inventory');
 await expect(page.getByLabel('Saved view')).toHaveValue('Night shift');
 await page.getByRole('button',{name:'Customize view',exact:true}).click();
 await drawer.getByLabel('Replenishment details',{exact:true}).uncheck();
 await drawer.getByRole('button',{name:'Move ledger up',exact:true}).click();
 await drawer.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Replenishment attention'})).not.toBeVisible();
 await expect(page.locator('.inventory-warning')).toBeVisible();
 await page.getByRole('button',{name:'Cards',exact:true}).click();
 await expect(page.locator('.inventory-cards')).toBeVisible();
 await page.locator('.operations-page').evaluate(el=>el.scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:'test-results/inventory-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'test-results/inventory-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.getByRole('button',{name:'Customize view',exact:true}).click();
 await drawer.getByRole('button',{name:'Reset',exact:true}).click();
 await drawer.getByRole('button',{name:'Save',exact:true}).click();
 await expect(page.locator('.goob-view')).toHaveClass(/theme-fieldbook/);
 await expect(page.locator('.inventory-table')).toBeVisible();
});
