"""Render the foundation baseline and dictionary from database.model."""
from pathlib import Path
from database.model import TABLES, ordered_tables

ROOT = Path(__file__).parent


def render():
    sql = ['-- Baseline: generated by python -m database.generate. Never rewrite after deployment.',
           'CREATE SCHEMA goob_foundation;', 'REVOKE CREATE ON SCHEMA goob_foundation FROM PUBLIC;',
           'SET LOCAL search_path TO goob_foundation, pg_catalog;']
    dictionary = ['# Table dictionary', '',
        'All business tables live in `goob_foundation`. Prefix = owning module. UUIDs identify records. '
        'Unless stated otherwise, `(organization_id,id)` is the primary key; '
        '`organization_id` references `org_organizations(id)`. Every FK uses `ON DELETE RESTRICT`; '
        'there are no cascading deletes. Every reference includes organization_id to reject cross-tenant links. '
        'NOT NULL denotes required columns; other columns are nullable. Every FK has an index. '
        'Non-history rows retain created_at; archive or use an explicit lifecycle status where provided. '
        'Changes to mutable business rows require application audit events in future integration. '
        'Append-only rows require a new version, reversal, or compensating record. '
        'The guarded demo reset is the only tooling path that deletes fixture history.', '']
    erd=['# Physical ERD', '', 'Generated from the same FK specification as migration 001. Composite tenant keys are omitted from arrows for readability.', '', '```mermaid', 'erDiagram']
    for name in ordered_tables():
        spec = TABLES[name]
        defs = [f'  {column} {typ}' for column,typ in spec['columns'].items()]
        pk = 'id' if name == 'org_organizations' else 'organization_id,id'
        defs.append(f'  PRIMARY KEY ({pk})')
        if name != 'org_organizations':
            defs.append('  FOREIGN KEY (organization_id) REFERENCES org_organizations(id) ON DELETE RESTRICT')
        for col, ref in spec['refs'].items():
            defs.append(f'  FOREIGN KEY (organization_id,{col}) REFERENCES {ref}(organization_id,id) ON DELETE RESTRICT')
            erd.append(f'  {ref} ||--o{{ {name} : "{col}"')
        for columns in spec['unique']:
            defs.append(f'  UNIQUE ({",".join(columns)})')
        defs.extend(f'  CHECK ({check})' for check in spec['checks'])
        sql.append(f'CREATE TABLE {name} (\n' + ',\n'.join(defs) + '\n);')
        for col in spec['refs']:
            sql.append(f'CREATE INDEX ON {name} (organization_id,{col});')
        lifecycle = 'Append-only; a trigger rejects UPDATE/DELETE.' if spec['history'] else 'Mutable operational record; FK-restricted deletion.'
        comment = f"Owner: {spec['owner']}. {lifecycle} {spec['note']}"
        sql.append(f"COMMENT ON TABLE {name} IS '{comment.replace(chr(39), chr(39)*2)}';")
        dictionary += [f'## {name}', '', f"Owner: **{spec['owner']}**. PK: `{pk}`. {lifecycle} {spec['note']}", '', '| Column | SQL type/default/nullability | Reference |', '|---|---|---|']
        for col, typ in spec['columns'].items():
            ref = spec['refs'].get(col, 'org_organizations.id' if col=='organization_id' else '')
            dictionary.append(f'| {col} | `{typ}` | {ref} |')
        dictionary += ['', 'Unique constraints: '+('; '.join('`'+','.join(x)+'`' for x in spec['unique']) or 'primary key only')+'.', '', 'Checks: '+('; '.join('`'+x+'`' for x in spec['checks']) or 'column checks above')+'.', '']
    sql.append('CREATE INDEX ON report_events (organization_id,occurred_at DESC,event_type);')
    sql.append('CREATE INDEX ON audit_events (organization_id,record_table,record_id,occurred_at DESC);')
    sql.append("CREATE INDEX ON job_appointments (organization_id,starts_at) WHERE status='scheduled';")
    sql.append("CREATE INDEX ON follow_tasks (organization_id,due_at) WHERE status='open';")
    sql.append("CREATE INDEX ON agree_benefit_reservations (organization_id,account_id) WHERE status='active';")
    sql.append("CREATE INDEX ON inv_reservations (organization_id,account_id) WHERE status='active';")
    dictionary += ['## Tooling tables', '',
       '`goob_db_meta.migrations`: version text PK, sha256 text NOT NULL, applied_at timestamptz NOT NULL. '
       'Database-owned migration history, no tenant. Checksums prevent silently rewriting applied SQL.', '',
       '`goob_db_meta.fixture_rows`: organization_id UUID, table_name text, record_id UUID, '
       'row_snapshot JSONB, as_of date; composite primary key (organization_id,table_name,record_id). '
       'Tooling-owned fixture manifest, no domain cascade or application dependency. '
       'Full snapshots detect edits and restrict reset to the exact known fixture set.', '',
       'Read models: `inv_balances`, `agree_balances`, `bill_invoice_reconciliation`. '
       'These views calculate from records and are never seeded. Additional integrity triggers '
       'and view definitions are in migrations 002 and 003; see INTEGRITY.md for their contracts.']
    erd += ['```', '']
    return '\n\n'.join(sql)+'\n', '\n'.join(line.rstrip() for line in dictionary), '\n'.join(erd)


def main():
    import argparse
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    outputs = zip([ROOT/'migrations/001_foundation.sql',ROOT/'docs/TABLES.md',ROOT/'docs/ERD.md'],render())
    for path, content in outputs:
        if args.check:
            if not path.exists() or path.read_text()!=content:
                raise SystemExit(f'Generated artifact differs: {path.name}')
        else:
            path.write_text(content)
    print(f'Schema artifacts consistent: {len(TABLES)} tables.')

if __name__=='__main__': main()
